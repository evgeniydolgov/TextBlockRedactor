import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { createDebouncedChange } from './createDebouncedChange'
import { paragraph } from '../testing/noteFixtures'

beforeEach(() => vi.useFakeTimers())
afterEach(() => vi.useRealTimers())

describe('createDebouncedChange', () => {
  it('waits for 1000ms of inactivity and delivers only the latest snapshot', () => {
    const callback = vi.fn()
    const change = createDebouncedChange(callback)
    const latest = [paragraph('123', 'Последний')]
    change.schedule([paragraph('123', 'Первый')])
    vi.advanceTimersByTime(700)
    change.schedule(latest)
    vi.advanceTimersByTime(999)
    expect(callback).not.toHaveBeenCalled()
    vi.advanceTimersByTime(1)
    expect(callback).toHaveBeenCalledExactlyOnceWith(latest)
    vi.runAllTimers()
    expect(callback).toHaveBeenCalledTimes(1)
  })

  it.each([undefined, -1, NaN, Infinity, -Infinity, 2147483648])('defaults invalid delay %s', delay => {
    const callback = vi.fn()
    createDebouncedChange(callback, delay).schedule([])
    vi.advanceTimersByTime(999)
    expect(callback).not.toHaveBeenCalled()
    vi.advanceTimersByTime(1)
    expect(callback).toHaveBeenCalledExactlyOnceWith([])
  })

  it('supports a custom delay and synchronous zero delay', () => {
    const callback = vi.fn()
    const change = createDebouncedChange(callback, 2000)
    change.schedule([])
    vi.advanceTimersByTime(1999)
    expect(callback).not.toHaveBeenCalled()
    vi.advanceTimersByTime(1)
    expect(callback).toHaveBeenCalledTimes(1)
    change.configure(callback, 0)
    change.schedule([])
    expect(callback).toHaveBeenCalledTimes(2)
    expect(vi.getTimerCount()).toBe(0)
  })

  it('restarts pending work when delay changes, including to zero', () => {
    const callback = vi.fn()
    const change = createDebouncedChange(callback)
    change.schedule([])
    vi.advanceTimersByTime(500)
    change.configure(callback, 2000)
    vi.advanceTimersByTime(1999)
    expect(callback).not.toHaveBeenCalled()
    vi.advanceTimersByTime(1)
    expect(callback).toHaveBeenCalledTimes(1)
    change.schedule([])
    change.configure(callback, 0)
    expect(callback).toHaveBeenCalledTimes(2)
  })

  it('updates callbacks without delaying pending work on rerenders', () => {
    const first = vi.fn()
    const current = vi.fn()
    const change = createDebouncedChange(first)
    change.schedule([])
    vi.advanceTimersByTime(500)
    change.configure(first)
    change.configure(current)
    vi.advanceTimersByTime(500)
    expect(first).not.toHaveBeenCalled()
    expect(current).toHaveBeenCalledExactlyOnceWith([])
  })

  it('cancels when callback is removed and ignores updates until enabled', () => {
    const callback = vi.fn()
    const change = createDebouncedChange(callback)
    change.schedule([])
    change.configure(undefined)
    change.schedule([])
    change.flush()
    vi.runAllTimers()
    expect(callback).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
    change.configure(callback, 0)
    change.schedule([])
    expect(callback).toHaveBeenCalledOnce()
  })

  it('flushes once and can be reused after cancellation', () => {
    const callback = vi.fn()
    const change = createDebouncedChange(callback)
    expect(vi.getTimerCount()).toBe(0)
    change.configure(callback, 2000)
    expect(vi.getTimerCount()).toBe(0)
    change.schedule([])
    change.flush()
    change.flush()
    vi.runAllTimers()
    expect(callback).toHaveBeenCalledOnce()
    change.schedule([])
    change.cancel()
    vi.runAllTimers()
    expect(callback).toHaveBeenCalledOnce()
    change.schedule([])
    vi.advanceTimersByTime(2000)
    expect(callback).toHaveBeenCalledTimes(2)
  })
})
